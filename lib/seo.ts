/** Safe JSON-LD payload (escapes `<` to avoid XSS in script tags). */
export function jsonLdString(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

export function breadcrumbJsonLd(items: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: item.name,
      item: item.path.startsWith("http") ? item.path : absoluteUrl(item.path),
    })),
  };
}

/** Twitter card matching an OG image so root layout twitter:image does not leak. */
export function twitterShare(
  title: string,
  description: string,
  imageUrl: string = DEFAULT_OG_IMAGE.url
) {
  return {
    card: "summary_large_image" as const,
    title,
    description,
    images: [imageUrl],
  };
}

/** OG + Twitter pair using the existing /og pipeline (no new card design). */
export function pageOg(opts: {
  title: string;
  description: string;
  path: string;
  kicker: string;
  tags?: string[];
  alt?: string;
  accent?: string;
}) {
  const url = ogImageUrl({
    kicker: opts.kicker,
    title: opts.title,
    description: opts.description,
    tags: opts.tags,
    accent: opts.accent,
    path: opts.path.replace(/^\//, ""),
  });
  return {
    images: [
      {
        url,
        width: 1200,
        height: 630,
        alt: opts.alt || opts.title,
      },
    ],
    twitter: twitterShare(opts.title, opts.description, url),
  };
}


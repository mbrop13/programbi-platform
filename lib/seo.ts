/** Tope de Google para el <title> completo, marca incluida. */
export const TITLE_MAX = 60;
export const TITLE_SUFFIX = " | ProgramBI";

/**
 * Arma un título final de hasta 60 caracteres con la marca al final.
 * Si el texto ya trae "| ProgramBI", no lo duplica.
 */
export function tituloSeo(texto: string, max = TITLE_MAX): string {
  const limpio = (texto || "").replace(/\s+/g, " ").trim();
  if (!limpio) return TITLE_SUFFIX.trim();
  const conMarcaYa = / \| ProgramBI$/i.test(limpio);
  const base = conMarcaYa ? limpio.replace(/ \| ProgramBI$/i, "") : limpio;
  const completo = `${base}${TITLE_SUFFIX}`;
  if (completo.length <= max) return completo;

  const disponible = Math.max(1, max - TITLE_SUFFIX.length);
  let corte = base.slice(0, disponible).trim();
  const ultimoEspacio = corte.lastIndexOf(" ");
  if (ultimoEspacio >= Math.floor(disponible * 0.6)) {
    corte = corte.slice(0, ultimoEspacio);
  }
  corte = corte.replace(/[\s:;,.\-–—|]+$/, "");
  return `${corte || base.slice(0, disponible)}${TITLE_SUFFIX}`;
}

/**
 * Título de una página de país, sin pasar de 60 caracteres y sin perder el
 * país. Primero intenta con la marca; si no cabe, deja el texto solo (que es
 * lo que mantiene «República Dominicana» dentro del límite); si aun así se
 * pasa, corta en palabra completa.
 */
export function tituloLocal(texto: string, max = TITLE_MAX): string {
  // «República Dominicana» no cabe con la marca: se usa su forma corta.
  const limpio = (texto || "")
    .replace(/República Dominicana/g, "Rep. Dominicana")
    .replace(/\s+/g, " ")
    .trim();
  if (!limpio) return TITLE_SUFFIX.trim();
  const base = limpio.replace(/ \| ProgramBI$/i, "");
  const completo = `${base}${TITLE_SUFFIX}`;
  if (completo.length <= max) return completo;
  if (base.length <= max) return base;
  let corte = base.slice(0, max).trim();
  const ultimoEspacio = corte.lastIndexOf(" ");
  if (ultimoEspacio >= Math.floor(max * 0.6)) corte = corte.slice(0, ultimoEspacio);
  corte = corte.replace(/[\s:;,.|\-–—]+$/, "");
  return corte || base.slice(0, max);
}

/** Path for <link rel="canonical">: no query, no hash. */
export function canonicalPath(path = "/"): string {
  const stripped = (path.split("#")[0] ?? "/").split("?")[0] ?? "/";
  if (!stripped || stripped === "/") return "/";
  return stripped.startsWith("/") ? stripped : `/${stripped}`;
}

export function absoluteUrl(path = "/"): string {
  if (/^https?:\/\//i.test(path)) {
    try {
      const url = new URL(path);
      if (url.hostname.toLowerCase() === "programbi.com") {
        url.protocol = "https:";
        url.hostname = CANONICAL_HOST;
        url.port = "";
        return url.toString();
      }
    } catch {
      /* keep original */
    }
    return path;
  }
  const clean = canonicalPath(path);
  if (clean === "/") return SITE_URL;
  return `${SITE_URL}${clean}`;
}

/** Sitemap/canonical loc: www only, no query/hash. Null if foreign host. */
export function sitemapLoc(pathOrUrl: string): string | null {
  const raw = pathOrUrl.trim();
  if (!raw) return null;
  if (/^https?:\/\//i.test(raw)) {
    try {
      const url = new URL(raw);
      const host = url.hostname.toLowerCase();
      if (host !== CANONICAL_HOST && host !== "programbi.com") return null;
      return absoluteUrl(url.pathname);
    } catch {
      return null;
    }
  }
  return absoluteUrl(raw);
}

